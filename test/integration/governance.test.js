  await assert.rejects(c.services.voice.turn(s.id, 'more', camp), /already ended/);
  await assert.rejects(c.services.voice.turn('nope', 'x', camp), /not found/);
  await assert.rejects(c.services.voice.get('nope'), /not found/);
  const h = await c.services.voice.getHandoff(done.handoffId);
