test('rules: maker-checker lifecycle with validation, four-eyes and rollback', async () => {
  const author = ACTOR('author-1', ['rule_author']);
  const approver = ACTOR('approver-1', ['rule_approver']);
  const scoring = await c.services.rules.get('scoring');
  const changed = structuredClone(scoring);
  changed.tiers.hot = 65;
  await assert.rejects(c.services.rules.createDraft({ kind: 'scoring', payload: { ...changed, tiers: { hot: 1, warm: 2 } } }, author), /invalid/);
  const draft = await c.services.rules.createDraft({ kind: 'scoring', payload: changed, description: 'lower hot threshold' }, author);
  assert.equal(draft.version_no, 2);
  await assert.rejects(c.services.rules.approve(draft.id, approver), /Only pending/);
  await assert.rejects(c.services.rules.submit(draft.id, approver), /Only the author/);
  await c.services.rules.submit(draft.id, author);
  await assert.rejects(c.services.rules.submit(draft.id, author), /Only drafts/);
  await assert.rejects(c.services.rules.approve(draft.id, author), /Maker-checker/);
  await assert.rejects(c.services.rules.reject(draft.id, author), /Maker-checker/);
  await c.services.rules.approve(draft.id, approver, { comment: 'ok' });
  assert.equal((await c.services.rules.get('scoring')).tiers.hot, 65);
  const v1 = await c.services.rules.byId('scoring@1');
  assert.equal(v1.status, 'retired');
  const rb = await c.services.rules.rollback('scoring@1', author);
  assert.equal(rb.status, 'draft');
  await c.services.rules.submit(rb.id, author);
  await c.services.rules.reject(rb.id, approver, { comment: 'not now' });
  assert.equal((await c.services.rules.byId(rb.id)).status, 'rejected');
  await assert.rejects(c.services.rules.reject(rb.id, approver), /Only pending/);
  const msgs = structuredClone(await c.services.rules.get('content.messages'));
  msgs.templates.first_reminder.vi = 'Giảm giá 20% khi gia hạn!';
  await assert.rejects(c.services.rules.createDraft({ kind: 'content.messages', payload: msgs }, author), (e) => e.details.some((d) => d.includes('copy guard')));
  assert.ok((await c.services.rules.list({ kind: 'scoring' })).length === 3);
  assert.ok((await c.services.rules.snapshot()).some((s) => s.kind === 'scoring' && s.version === 2));
  assert.deepEqual(await c.services.rules.validate('scoring', scoring), []);
  await assert.rejects(c.services.rules.byId('nope@1'), /not found/);
  await assert.rejects(c.services.rules.get('nope'), /not found/);
  const actions = (await c.services.audit.list({ limit: 200 })).map((a) => a.action);
  for (const a of ['rules.draft_created', 'rules.submitted', 'rules.approved', 'rules.rejected']) assert.ok(actions.includes(a), a);
});

test('identity: login, MFA, lockout, password change, user admin', async () => {
  const r = await c.services.identity.login({ username: 'campaign', password: 'Tasco@Demo2026!' }, { ip: '1.1.1.1' });
  assert.ok(r.accessToken);
  assert.ok(r.user.permissions.includes('journeys:run'));
  const principal = await c.services.identity.authenticate(r.accessToken);
  assert.equal(principal.username, 'campaign');
  c.services.identity.logout(principal.claims);
  assert.equal(await c.services.identity.authenticate(r.accessToken), null, 'revoked token rejected');
  const mfa = await c.services.identity.login({ username: 'approver', password: 'Tasco@Demo2026!' });
  assert.equal(mfa.mfaRequired, true);
  await assert.rejects(c.services.identity.verifyMfa({ mfaToken: mfa.mfaToken, code: '000000' }), /Invalid code/);
  await assert.rejects(c.services.identity.verifyMfa({ mfaToken: 'bad', code: '123456' }), /expired/);
  const secret = await c.services.identity.getTotpSecretForDemo('approver');
  const ok = await c.services.identity.verifyMfa({ mfaToken: mfa.mfaToken, code: totp(secret) });
  assert.ok(ok.accessToken);
  await assert.rejects(c.services.identity.login({ username: 'nobody', password: 'x' }), /Invalid username or password/);
  for (let i = 0; i < 5; i++) await assert.rejects(c.services.identity.login({ username: 'exec', password: 'wrong' }));
  await assert.rejects(c.services.identity.login({ username: 'exec', password: 'Tasco@Demo2026!' }), /locked/);
  const admin = ACTOR('admin-x', ['admin']);
  await assert.rejects(c.services.identity.createUser({ username: 'weak', password: 'short', displayName: 'W', roles: ['executive'] }, admin), /Password policy/);
  await assert.rejects(c.services.identity.createUser({ username: 'x', password: 'long enough pw', displayName: 'X', roles: ['god'] }, admin), /Unknown role/);
  const created = await c.services.identity.createUser({ username: 'new.agent', password: 'long enough pw', displayName: 'N', roles: ['telesales_agent'], region: 'Hà Nội' }, admin);
  await assert.rejects(c.services.identity.createUser({ username: 'new.agent', password: 'long enough pw', displayName: 'N', roles: ['telesales_agent'] }, admin), /exists/);
  const upd = await c.services.identity.update(created.user.id, { status: 'disabled' }, admin);
  assert.equal(upd.status, 'disabled');
  await assert.rejects(c.services.identity.login({ username: 'new.agent', password: 'long enough pw' }), /Invalid/);
  await assert.rejects(c.services.identity.update('nope', {}, admin), /not found/);
  await assert.rejects(c.services.identity.update(created.user.id, { roles: ['god'] }, admin), /Unknown role/);
  const me = (await c.services.identity.list()).find((u) => u.username === 'admin');
  await assert.rejects(c.services.identity.update(me.id, { roles: ['executive'] }, { ...admin, id: me.id }), /own admin role/);
  const camp = (await c.services.identity.list()).find((u) => u.username === 'campaign');
  await c.services.identity.changePassword(camp.id, { currentPassword: 'Tasco@Demo2026!', newPassword: 'A much longer pass 1' });
  await assert.rejects(c.services.identity.changePassword(camp.id, { currentPassword: 'wrong', newPassword: 'whatever long' }), /incorrect/);
  await assert.rejects(c.services.identity.changePassword(camp.id, { currentPassword: 'A much longer pass 1', newPassword: 'short' }), /Password policy/);
  assert.equal(await c.services.identity.authenticate('garbage'), null);
});

